def months_to_target(pv, pmt, annual_rate, fv, max_months=1200):
    if fv <= pv:
        return 0
    r = annual_rate / 12
    if pmt <= 0 and r <= 0:
        return None
    for n in range(1, max_months + 1):
        if r > 0:
            value = pv * (1 + r) ** n + pmt * (((1 + r) ** n - 1) / r)
        else:
            value = pv + pmt * n
        if value >= fv:
            return n
    return None

